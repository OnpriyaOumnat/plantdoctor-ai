def conf_level(c):
    if c >= 0.70: return "สูง"
    if c >= 0.40: return "ปานกลาง"
    return "ต่ำ (ควรถ่ายภาพซ้ำหรือให้ผู้เชี่ยวชาญตรวจ)"

def explain(r):
    n = len(r.boxes)
    if n == 0:
        return "ไม่พบใบไม้หรือโรคที่โมเดลรู้จัก ลองถ่ายภาพให้ชัดขึ้นหรือใกล้ใบมากขึ้น"
    order = sorted(range(n), key=lambda i: -float(r.boxes.conf[i]))
    lines = [f"พบ {n} จุดที่ตรวจจับได้ (เรียงตามความมั่นใจ)", "-" * 50]
    for k, i in enumerate(order, 1):
        name = r.names[int(r.boxes.cls[i])]
        c = float(r.boxes.conf[i])
        plant_th, plant_en, cond, kind, symptom, advice = DISEASE_INFO.get(
            name, (name, name, name, "ไม่ทราบ", "-", "-"))
        lines += [
            f"[{k}] พืช: {plant_th} ({plant_en})",
            f"    ผลการตรวจ: {cond}",
            f"    ประเภท: {kind}",
            f"    ความมั่นใจ: {c:.0%} ({conf_level(c)})",
            f"    ลักษณะอาการ: {symptom}",
            f"    คำแนะนำเบื้องต้น: {advice}",
            "",
        ]
    lines.append("หมายเหตุ: เป็นผลจากโมเดลต้นแบบ ใช้ประกอบการตัดสินใจเท่านั้น ไม่ใช่การวินิจฉัยทางการเกษตร")
    return "\n".join(lines)


